"""SHAP Explainability Service for Fraud Detection Models.

FraudGuard AI – Explainable Fraud Detection System

IMPORTANT REAL-MODEL EXPLAINABILITY NOTICE:
--------------------------------------------
In non-demo mode, feature contributions generated by this service are extracted
directly from real mathematical Shapley values calculated by `shap.TreeExplainer`
on the trained machine learning model (e.g. XGBoost / Random Forest).

The SHAP values MUST NEVER be hardcoded or statically assigned in production mode.
Each attribution represents the exact marginal shift (in margin / log-odds space)
that a specific transaction feature causes toward predicting fraud (positive attribution,
"increases_risk") or toward predicting legitimate activity (negative attribution,
"decreases_risk").

If model artifacts are missing or if an incompatible non-tree classifier is loaded,
the service falls back gracefully to a heuristic-based demo mode, explicitly signaling
`is_demo = True`.
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

import joblib
import numpy as np
import pandas as pd
import shap

from app.core.config import get_settings
from app.schemas.transaction import FeatureContribution, TransactionInput

logger = logging.getLogger("fraudguard.explain_service")

# Exact feature ordering expected by the trained preprocessing pipeline
FEATURE_ORDER: List[str] = [
    "amount",
    "hour_of_day",
    "old_balance_origin",
    "new_balance_origin",
    "old_balance_dest",
    "new_balance_dest",
    "transaction_type",
]


def extract_positive_class_shap(
    shap_output: Union[List[np.ndarray], np.ndarray, Any]
) -> np.ndarray:
    """Normalize and extract SHAP attribution values for the positive (fraud) class.

    Handles diverse SHAP output formats across different model architectures:
    - List of arrays per class (e.g. Random Forest binary classification `[class_0, class_1]`):
      The second array (index 1) is selected for the fraud class.
    - 3D array of shape `(n_samples, n_features, n_classes)`:
      Index 1 along the class axis is selected.
    - 2D array of shape `(n_samples, n_features)`:
      Standard single-output format (e.g. XGBoost binary margin/log-odds).
    - `shap.Explanation` object with `.values` attribute.

    Parameters
    ----------
    shap_output : list or np.ndarray or shap.Explanation
        Raw output returned by `TreeExplainer.shap_values()`.

    Returns
    -------
    np.ndarray
        2D array `(n_samples, n_features)` or 1D array of positive class attributions.
    """
    if isinstance(shap_output, list):
        # Multi-output / Random Forest list format: [class_0_array, class_1_array]
        pos_values = shap_output[1] if len(shap_output) > 1 else shap_output[0]
    elif isinstance(shap_output, np.ndarray):
        if shap_output.ndim == 3 and shap_output.shape[-1] >= 2:
            pos_values = shap_output[..., 1]
        else:
            pos_values = shap_output
    elif hasattr(shap_output, "values"):
        # shap.Explanation object returned by newer SHAP API
        vals = shap_output.values
        if isinstance(vals, list):
            pos_values = vals[1] if len(vals) > 1 else vals[0]
        elif vals.ndim == 3 and vals.shape[-1] >= 2:
            pos_values = vals[..., 1]
        else:
            pos_values = vals
    else:
        pos_values = np.asarray(shap_output)

    return pos_values


class ExplainService:
    """Service providing local SHAP-based feature attributions for fraud predictions.

    Attributes
    ----------
    model : Any
        Trained tree-based classifier (e.g. XGBClassifier, RandomForestClassifier).
    preprocessor : Any
        Fitted scikit-learn ColumnTransformer instance.
    explainer : shap.TreeExplainer, optional
        Initialized TreeExplainer for calculating Shapley attributions.
    feature_names : list of str
        Transformed feature names corresponding to the preprocessor columns.
    is_demo : bool
        Flag indicating if the service is running in fallback heuristic demo mode.
    """

    def __init__(
        self,
        model: Optional[Any] = None,
        preprocessor: Optional[Any] = None,
        feature_names: Optional[List[str]] = None,
    ) -> None:
        self.model: Optional[Any] = model
        self.preprocessor: Optional[Any] = preprocessor
        self.explainer: Optional[shap.TreeExplainer] = None
        self.feature_names: List[str] = feature_names or []
        self.is_demo: bool = True
        self._initialized: bool = False

    def load_artifacts(self) -> None:
        """Load model, preprocessor, and feature names, and initialize TreeExplainer.

        If the model files are missing or if the model is not a tree-based ensemble,
        the service falls back gracefully to deterministic demo mode (`is_demo = True`).
        """
        settings = get_settings()
        backend_dir = Path(__file__).resolve().parent.parent.parent
        project_root = backend_dir.parent

        model_rel = settings.MODEL_PATH.replace("\\", "/")
        prep_rel = settings.PREPROCESSOR_PATH.replace("\\", "/")
        feat_rel = getattr(settings, "FEATURE_NAMES_PATH", "models/feature_names.json").replace("\\", "/")

        model_candidates = [
            Path(model_rel),
            backend_dir / model_rel,
            project_root / "ml" / model_rel,
            project_root / model_rel,
            project_root / "ml" / "models" / "fraud_model.joblib",
            backend_dir / "models" / "fraud_model.joblib",
        ]

        prep_candidates = [
            Path(prep_rel),
            backend_dir / prep_rel,
            project_root / "ml" / prep_rel,
            project_root / prep_rel,
            project_root / "ml" / "models" / "preprocessor.joblib",
            backend_dir / "models" / "preprocessor.joblib",
        ]

        feat_candidates = [
            Path(feat_rel),
            backend_dir / feat_rel,
            project_root / feat_rel,
            project_root / "ml" / "models" / "feature_names.json",
            backend_dir / "models" / "feature_names.json",
            backend_dir / "models" / "features.json",
        ]


        resolved_model_path = next((p for p in model_candidates if p.exists() and p.is_file()), None)
        resolved_prep_path = next((p for p in prep_candidates if p.exists() and p.is_file()), None)
        resolved_feat_path = next((p for p in feat_candidates if p.exists() and p.is_file()), None)

        if resolved_model_path and resolved_prep_path:
            try:
                logger.info("Loading preprocessor for ExplainService from %s...", resolved_prep_path)
                self.preprocessor = joblib.load(resolved_prep_path)

                logger.info("Loading model for ExplainService from %s...", resolved_model_path)
                self.model = joblib.load(resolved_model_path)

                # Load feature names list
                if resolved_feat_path:
                    with open(resolved_feat_path, "r", encoding="utf-8") as f:
                        self.feature_names = json.load(f)
                elif hasattr(self.preprocessor, "get_feature_names_out"):
                    self.feature_names = list(self.preprocessor.get_feature_names_out())

                # Attempt to initialize TreeExplainer on the loaded model
                logger.info("Initializing shap.TreeExplainer for model %s...", type(self.model).__name__)
                self.explainer = shap.TreeExplainer(self.model)

                self.is_demo = False
                self._initialized = True
                logger.info("ExplainService successfully initialized with real TreeExplainer.")
                return

            except Exception as exc:
                logger.warning(
                    "Model is not tree-based or failed TreeExplainer initialization: %s. "
                    "Reverting ExplainService to demo mode.",
                    exc,
                )
                self.explainer = None
                self.is_demo = True
                self._initialized = True
                return

        # Fallback if artifact files are not found
        self.is_demo = True
        self.explainer = None
        self._initialized = True
        logger.warning(
            "Model or preprocessor artifacts not found at configured paths. "
            "ExplainService is running in DEMO MODE with heuristic feature contributions."
        )

    def explain(
        self,
        transaction_df: Union[pd.DataFrame, TransactionInput, Dict[str, Any]],
    ) -> List[FeatureContribution]:
        """Explain a transaction by returning the top 5 risk drivers for the fraud class.

        Parameters
        ----------
        transaction_df : pd.DataFrame or TransactionInput or dict
            Raw transaction features.

        Returns
        -------
        list of FeatureContribution
            Top 5 features sorted in descending order of absolute SHAP value.
            Each item includes `feature`, `shap_value` (rounded to 4 decimals),
            and `direction` ("increases_risk" if shap_value > 0 else "decreases_risk").
        """
        if not self._initialized:
            self.load_artifacts()

        # Align input payload into a standardized single-row DataFrame
        df_aligned = self._prepare_dataframe(transaction_df)

        if self.is_demo or self.explainer is None or self.preprocessor is None:
            return self._compute_demo_contributions(df_aligned)

        return self._compute_model_contributions(df_aligned)

    def explain_record(
        self,
        transaction_df: Union[pd.DataFrame, TransactionInput, Dict[str, Any]],
    ) -> Dict[str, Any]:
        """Helper returning both top feature contributions and the `is_demo` state."""
        contributions = self.explain(transaction_df)
        return {
            "top_features": contributions,
            "is_demo": self.is_demo,
        }

    # ========================================================================
    # REAL MODEL EXPLANATION ENGINE (NON-DEMO MODE)
    # ------------------------------------------------------------------------
    # All values here are computed directly from the fitted ColumnTransformer
    # and the shap.TreeExplainer. THEY ARE NEVER HARDCODED.
    # ========================================================================
    def _compute_model_contributions(self, df: pd.DataFrame) -> List[FeatureContribution]:
        """Compute real SHAP feature attributions using the fitted preprocessor and TreeExplainer."""
        # 1. Transform raw transaction features into the model's numerical feature space
        X_transformed = self.preprocessor.transform(df)

        # 2. Calculate SHAP values for the transformed instance
        shap_raw = self.explainer.shap_values(X_transformed)

        # 3. Extract attribution values for the positive (fraud) class
        pos_values = extract_positive_class_shap(shap_raw)

        # Extract 1D attribution vector for the evaluated instance
        if pos_values.ndim > 1:
            shap_vector = pos_values[0]
        else:
            shap_vector = pos_values

        # 4. Resolve feature names matching the transformed columns
        feature_names = self.feature_names
        if not feature_names or len(feature_names) != len(shap_vector):
            if hasattr(self.preprocessor, "get_feature_names_out"):
                feature_names = list(self.preprocessor.get_feature_names_out())
            else:
                feature_names = [f"feature_{i}" for i in range(len(shap_vector))]

        # 5. Merge one-hot encoded transaction_type columns into a single unified contribution
        # e.g. transaction_type_TRANSFER, transaction_type_CASH_OUT -> transaction_type
        merged_contributions: Dict[str, float] = {}
        for fname, sval in zip(feature_names, shap_vector):
            val_float = float(sval)
            # Remove transformer prefix if present (e.g. cat__transaction_type_*)
            clean_name = fname.split("__")[-1] if "__" in fname else fname

            if clean_name.startswith("transaction_type"):
                merged_contributions["transaction_type"] = (
                    merged_contributions.get("transaction_type", 0.0) + val_float
                )
            else:
                merged_contributions[clean_name] = val_float

        # 6. Rank features by absolute SHAP magnitude (strongest risk drivers first)
        ranked = sorted(
            merged_contributions.items(),
            key=lambda item: abs(item[1]),
            reverse=True,
        )

        # 7. Construct top 5 FeatureContribution schemas
        # Direction: "increases_risk" if shap_value > 0 else "decreases_risk"
        # Round shap_value to exactly 4 decimal places
        top_contributions: List[FeatureContribution] = []
        for feat, sval in ranked[:5]:
            rounded_val = round(float(sval), 4)
            direction = "increases_risk" if rounded_val > 0 else "decreases_risk"
            top_contributions.append(
                FeatureContribution(
                    feature=feat,
                    shap_value=rounded_val,
                    direction=direction,
                )
            )

        return top_contributions

    # ========================================================================
    # DEMO MODE HEURISTIC ENGINE (FALLBACK MODE)
    # ------------------------------------------------------------------------
    # Used only when model artifacts are absent or non-tree models are loaded.
    # Evaluates intuitive domain heuristics and flags `is_demo = True`.
    # ========================================================================
    def _compute_demo_contributions(self, df: pd.DataFrame) -> List[FeatureContribution]:
        """Deterministic domain-heuristic contributions for demo mode."""
        row = df.iloc[0].to_dict()
        amount = float(row.get("amount", 0.0))
        hour_of_day = int(row.get("hour_of_day", 12))
        old_balance_origin = float(row.get("old_balance_origin", 0.0))
        new_balance_origin = float(row.get("new_balance_origin", 0.0))
        old_balance_dest = float(row.get("old_balance_dest", 0.0))
        new_balance_dest = float(row.get("new_balance_dest", 0.0))
        transaction_type = str(row.get("transaction_type", "PAYMENT")).upper()

        contributions_dict: Dict[str, float] = {}

        # 1. Origin account balance depletion
        if new_balance_origin == 0.0 and old_balance_origin > 0.0:
            contributions_dict["old_balance_origin"] = 1.8420
            contributions_dict["new_balance_origin"] = 0.7250
        elif old_balance_origin > 100_000:
            contributions_dict["old_balance_origin"] = 0.6120
            contributions_dict["new_balance_origin"] = -0.4530
        else:
            contributions_dict["old_balance_origin"] = -0.3850
            contributions_dict["new_balance_origin"] = -0.5210

        # 2. High-risk transaction type (TRANSFER / CASH_OUT)
        if transaction_type in ("TRANSFER", "CASH_OUT"):
            contributions_dict["transaction_type"] = 1.4850
        elif transaction_type in ("PAYMENT", "CASH_IN", "DEBIT"):
            contributions_dict["transaction_type"] = -0.9230
        else:
            contributions_dict["transaction_type"] = 0.1500

        # 3. High transaction amount
        if amount >= 200_000:
            contributions_dict["amount"] = 1.2750
        elif amount >= 50_000:
            contributions_dict["amount"] = 0.6510
        else:
            contributions_dict["amount"] = -0.5840

        # 4. Off-peak night hours
        if hour_of_day in (0, 1, 2, 3, 4, 5, 23):
            contributions_dict["hour_of_day"] = 0.8920
        else:
            contributions_dict["hour_of_day"] = -0.4630

        # 5. Destination account balance activity
        if old_balance_dest == 0.0 and new_balance_dest == 0.0:
            contributions_dict["old_balance_dest"] = 0.3810
            contributions_dict["new_balance_dest"] = 0.2940
        elif new_balance_dest > old_balance_dest:
            contributions_dict["new_balance_dest"] = 0.3540
            contributions_dict["old_balance_dest"] = -0.2180
        else:
            contributions_dict["old_balance_dest"] = -0.1940
            contributions_dict["new_balance_dest"] = -0.2350

        # Rank by absolute magnitude
        ranked = sorted(
            contributions_dict.items(),
            key=lambda item: abs(item[1]),
            reverse=True,
        )

        top_contributions: List[FeatureContribution] = []
        for feat, sval in ranked[:5]:
            rounded_val = round(float(sval), 4)
            direction = "increases_risk" if rounded_val > 0 else "decreases_risk"
            top_contributions.append(
                FeatureContribution(
                    feature=feat,
                    shap_value=rounded_val,
                    direction=direction,
                )
            )

        return top_contributions

    @staticmethod
    def _prepare_dataframe(
        raw_input: Union[pd.DataFrame, TransactionInput, Dict[str, Any]],
    ) -> pd.DataFrame:
        """Validate, extract, and order features into the expected DataFrame schema."""
        if isinstance(raw_input, TransactionInput):
            row = {col: getattr(raw_input, col) for col in FEATURE_ORDER}
            df = pd.DataFrame([row])
        elif isinstance(raw_input, dict):
            record = raw_input.copy()
            if "step" in record and "hour_of_day" not in record:
                record["hour_of_day"] = int(record["step"]) % 24
            df = pd.DataFrame([record])
        elif isinstance(raw_input, pd.DataFrame):
            if raw_input.empty:
                raise ValueError("Cannot explain an empty DataFrame.")
            df = raw_input.iloc[[0]].copy()
            if "step" in df.columns and "hour_of_day" not in df.columns:
                df["hour_of_day"] = df["step"].astype(int) % 24
        else:
            raise TypeError(f"Unsupported transaction input type: {type(raw_input)}")

        missing = [col for col in FEATURE_ORDER if col not in df.columns]
        if missing:
            raise ValueError(f"Transaction input missing required features: {missing}")

        return df[FEATURE_ORDER]


# Global singleton instance
_explain_service_instance: Optional[ExplainService] = None


def get_explain_service() -> ExplainService:
    """Return the global ExplainService singleton instance."""
    global _explain_service_instance
    if _explain_service_instance is None:
        _explain_service_instance = ExplainService()
    return _explain_service_instance
